-- Supabase pgvector schema and RPC for AgriAssist Seva AI
-- Also includes Agmarknet market prices table and seed data

-- 1. Drop existing 3072-dim schemes table
DROP TABLE IF EXISTS schemes CASCADE;

-- 2. Recreate schemes table with 768 dimensions for EmbeddingGemma
CREATE TABLE schemes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT,
    eligibility TEXT,
    region TEXT,
    crop_type TEXT,
    embedding VECTOR(768)
);

-- 3. Recreate the match_schemes search RPC
CREATE OR REPLACE FUNCTION match_schemes (
  query_embedding VECTOR(768),
  match_threshold FLOAT,
  match_count INT,
  p_region TEXT DEFAULT NULL,
  p_land_size TEXT DEFAULT NULL
) RETURNS TABLE (
  id BIGINT,
  title TEXT,
  description TEXT,
  eligibility TEXT,
  region TEXT,
  crop_type TEXT,
  similarity FLOAT
) LANGUAGE plpgsql AS $$
BEGIN
  RETURN QUERY
  SELECT
    s.id,
    s.title,
    s.description,
    s.eligibility,
    s.region,
    s.crop_type,
    1 - (s.embedding <=> query_embedding) AS similarity
  FROM schemes s
  WHERE 1 - (s.embedding <=> query_embedding) > match_threshold
    AND (p_region IS NULL OR s.region = ANY(string_to_array(p_region, ',')))
    AND (p_land_size IS NULL OR s.description LIKE '%' || p_land_size || '%')
  ORDER BY s.embedding <=> query_embedding
  LIMIT match_count;
END;
$$;

-- 4. Create Agmarknet market prices table
CREATE TABLE IF NOT EXISTS agmarknet_market_prices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    commodity TEXT NOT NULL,
    market TEXT NOT NULL,
    arrival_date DATE NOT NULL,
    min_price FLOAT,
    max_price FLOAT,
    modal_price FLOAT,
    UNIQUE(commodity, market, arrival_date)
);

